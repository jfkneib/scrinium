                "Réglages de votre extension :\n"
                "• ctx.reglages.get(\"cle\", defaut) / .set(\"cle\", valeur) : enregistrés dans settings.json (en clair : jamais de mot de passe).\n"
                "• ctx.dossier_donnees : un dossier à vous (modèles, caches), créé quand vous en avez besoin.\n"
                "\n"
