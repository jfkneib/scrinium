                "• afficher_fiche(vue) : affiche la fenêtre sur cette fiche.\n"
                "• Texte de la fiche ouverte : texte_selectionne(), texte_complet(), inserer_texte(t), ajouter_a_la_fin(t), remplacer_tout(t) (annulables avec Ctrl+Z ; False si la fiche n'est pas modifiable).\n"
                "\n"
                "Les icônes sont des noms du thème d'icônes du système (ex. « mail-send », « edit-find »).\n"
