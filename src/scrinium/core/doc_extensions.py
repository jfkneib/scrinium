                "    ctx.ui.ajouter_panneau(\"Mots\", self.etiquette)\n"
                "    ctx.on(\"fiche_enregistree\", self.maj)\n"
                "\n"
                "def maj(self, fiche, **kw):\n"
                "    self.etiquette.setText(f\"{len((fiche.texte or '').split())} mots\")\n"
