                "• ctx.maj_meta(vue, cle=\"valeur\") garde des métadonnées avec la fiche (une ligne invisible en tête du texte ; chiffrées si la fiche est verrouillée ; None efface la clé).\n"
                "• ctx.assurer_identifiant(vue) : identifiant stable de la fiche (survit aux renommages, déplacements, verrouillage).\n"
                "\n"
                "Images jointes :\n"
                "• ctx.pieces(vue) : liste de pièces (id, nom, type, taille, ocr…).\n"
