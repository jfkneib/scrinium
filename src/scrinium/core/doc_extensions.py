                "• Gardez activer() rapide : ouvrez les fichiers et le réseau plus tard, pas au démarrage.\n"
                "• Testez ctx.ui is not None avant d'ajouter quoi que ce soit à la fenêtre.\n"
                "• N'écrivez jamais de secret (mot de passe, jeton) dans ctx.reglages : settings.json est un fichier en clair. Utilisez le trousseau du système (module « keyring ») comme le fait l'extension Partage.\n"
