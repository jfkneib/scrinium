"""Thème « Doc » : fiches qui expliquent comment écrire une extension (plugin) de Scrinium.

Proposé au premier lancement, et à la demande (menu Aide > « Documentation des extensions »), sans jamais écraser une fiche
que l'utilisateur aurait modifiée."""
